function shuffleArray(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

export function getAllDemoQuestions() {
  return shuffleArray(questions)
}

/* ── Vérification des réponses ──────────────────────────────
   Les bonnes réponses ne sont plus stockées en clair : chaque
   question porte l'empreinte de la sienne. Cela empêche de lire
   le corrigé directement dans le code du site.
   Ce n'est PAS une protection cryptographique — seul un contrôle
   côté serveur le serait — mais cela retire le corrigé prêt à
   l'emploi du bundle.                                          */

const SALT = 'aq7:'

function fnv1a(str) {
  let h = 0x811c9dc5
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i)
    h = Math.imul(h, 0x01000193) >>> 0
  }
  return h >>> 0
}

export function isCorrect(question, answer) {
  return fnv1a(SALT + question.id + '|' + answer) === question.answerHash
}
